const STAFF_MANAGE = ["admin", "industrial_agent"] as const;

function specializedTab(label: string, fields: SettingTabDef["fields"]): SettingTabDef {
  return { id: "specialized", label, fields };
}

function notificationsMiniTab(defaults?: {
  notifyOnReply?: boolean;
  notifyOnStatus?: boolean;
  escalateDays?: number;
}): SettingTabDef {
  return {
    id: "notifications",
    label: "الإشعارات",
    fields: [
      field({
        key: "notifyOnReply",
        path: "specialized.notifyOnReply",
        label: "إشعار عند الرد / الحدث",
        type: "boolean",
        defaultValue: defaults?.notifyOnReply ?? true,
      }),
      field({
        key: "notifyOnStatus",
        path: "specialized.notifyOnStatusChange",
        label: "إشعار عند تغيير الحالة",
        type: "boolean",
        defaultValue: defaults?.notifyOnStatus ?? true,
      }),
      field({
        key: "escalateDays",
        path: "specialized.escalateAfterDays",
        label: "أيام التصعيد عند التعطل",
        type: "number",
        defaultValue: defaults?.escalateDays ?? 7,
        min: 0,
        max: 90,
      }),
    ],
  };
}

